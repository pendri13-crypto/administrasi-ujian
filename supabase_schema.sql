-- ============================================================
-- SKEMA DATABASE ADMINISTRASI UJIAN (SUPABASE POSTGRESQL)
-- ============================================================

-- 1. Tabel Tahun Ajaran
CREATE TABLE IF NOT EXISTS tahun_ajaran (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(20) NOT NULL, -- contoh: '2026/2027'
    semester VARCHAR(10) NOT NULL CHECK (semester IN ('Ganjil', 'Genap')),
    status_aktif BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabel Kelas
CREATE TABLE IF NOT EXISTS kelas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kelas VARCHAR(30) NOT NULL, -- contoh: 'X MIPA 1'
    tingkat VARCHAR(10) NOT NULL,    -- contoh: '10'
    jurusan VARCHAR(50),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabel Siswa
CREATE TABLE IF NOT EXISTS siswa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nisn VARCHAR(20) NOT NULL UNIQUE,
    nis VARCHAR(20),
    nama_lengkap VARCHAR(150) NOT NULL,
    jenis_kelamin VARCHAR(1) NOT NULL CHECK (jenis_kelamin IN ('L', 'P')),
    kelas_id BIGINT REFERENCES kelas(id) ON DELETE CASCADE,
    foto_url TEXT, -- URL file foto dari Supabase Storage
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabel Mata Pelajaran
CREATE TABLE IF NOT EXISTS mapel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_mapel VARCHAR(20) NOT NULL UNIQUE,
    nama_mapel VARCHAR(100) NOT NULL,
    kkm NUMERIC(5, 2) DEFAULT 75.00,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Tabel Ruang Ujian
CREATE TABLE IF NOT EXISTS ruang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_ruang VARCHAR(20) NOT NULL UNIQUE,
    nama_ruang VARCHAR(100) NOT NULL,
    kapasitas INT DEFAULT 20,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tabel Ujian (Agenda)
CREATE TABLE IF NOT EXISTS ujian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tahun_ajaran_id BIGINT REFERENCES tahun_ajaran(id) ON DELETE CASCADE,
    nama_ujian VARCHAR(150) NOT NULL, -- contoh: 'Penilaian Akhir Semester (PAS)'
    jenis_ujian VARCHAR(20) NOT NULL CHECK (jenis_ujian IN ('PTS', 'PAS', 'PAT', 'US', 'Simulasi')),
    tgl_mulai DATE NOT NULL,
    tgl_selesai DATE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Tabel Jadwal Ujian
CREATE TABLE IF NOT EXISTS jadwal_ujian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ujian_id BIGINT REFERENCES ujian(id) ON DELETE CASCADE,
    mapel_id BIGINT REFERENCES mapel(id) ON DELETE CASCADE,
    tanggal DATE NOT NULL,
    jam_mulai TIME NOT NULL,
    jam_selesai TIME NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Tabel Peserta Ujian
CREATE TABLE IF NOT EXISTS peserta_ujian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ujian_id BIGINT REFERENCES ujian(id) ON DELETE CASCADE,
    siswa_id BIGINT REFERENCES siswa(id) ON DELETE CASCADE,
    no_peserta VARCHAR(50) NOT NULL,
    ruang_id BIGINT REFERENCES ruang(id) ON DELETE SET NULL,
    no_meja INT,
    sesi INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_ujian_siswa UNIQUE (ujian_id, siswa_id),
    CONSTRAINT uq_ujian_no_peserta UNIQUE (ujian_id, no_peserta)
);

-- 9. Tabel Nilai Ujian
CREATE TABLE IF NOT EXISTS nilai_ujian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peserta_ujian_id BIGINT REFERENCES peserta_ujian(id) ON DELETE CASCADE,
    jadwal_ujian_id BIGINT REFERENCES jadwal_ujian(id) ON DELETE CASCADE,
    nilai_pg NUMERIC(5, 2) DEFAULT 0.00,
    nilai_esai NUMERIC(5, 2) DEFAULT 0.00,
    nilai_akhir NUMERIC(5, 2) NOT NULL,
    keterangan VARCHAR(20) DEFAULT 'Hadir' CHECK (keterangan IN ('Hadir', 'Susulan', 'Tidak Hadir')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_peserta_jadwal UNIQUE (peserta_ujian_id, jadwal_ujian_id)
);

